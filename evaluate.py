PIECE_TO_PI = {
    'p': pawn_pi,
    'n': knight_pi,
    'b': bishop_pi,
    'r': rook_pi,
    'q': queen_pi
}

def game_phase(board): #returns the phase of the game
    p=0
    for r in range(8):
        for c in range(8):
            piece = board.board[r][c].lower()
            if piece == '-':
                continue
            if piece in PIECE_PHASES:
                p+= PIECE_PHASES[piece]
    return min(p, max_phase)

def evaluate(board):
    score = 0

    phase = game_phase(board)
    for r in range(8):
        for c in range(8):
            piece = board.board[r][c]
            if piece == '-':
                 continue

            if piece.isupper():
                p = piece.lower()
                score += PIECE_VALUES[p]
                if p == 'k':
                    beginning = king_middle_pi[r][c]
                    end = king_end_pi[r][c]
                    average = (beginning * phase + end * (max_phase-phase)) // max_phase
                    score += average
                else:
                    score+=PIECE_TO_PI[p][r][c]
            else:
                score -= PIECE_VALUES[piece]
                if piece == 'k':
                    beginning = king_middle_pi[7-r][c]
                    end = king_end_pi[7-r][c]
                    average = (beginning * phase + end * (max_phase-phase)) // max_phase
                    score -= average
                else:
                    score -= PIECE_TO_PI[piece][7-r][c]

    return score

